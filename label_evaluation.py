#!/usr/bin/env python3
"""
Label Quality Evaluation Script

Compares autogenerated labels from Delphi with golden standard labels.
Provides multiple evaluation metrics including semantic similarity, conciseness, and LLM judging.
"""

import argparse
import json
import orjson
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple, Optional
import pandas as pd
import numpy as np

def extract_golden_features(golden_graph_path: Path) -> Dict[Tuple[str, int], str]:
    """Extract feature->label mapping from golden labels graph."""
    with open(golden_graph_path, 'rb') as f:
        golden = orjson.loads(f.read())
    
    golden_features = {}
    for node in golden.get('nodes', []):
        if node.get('feature') is not None and 'clerp' in node:
            key = (str(node.get('layer')), int(node.get('feature')))
            golden_features[key] = node.get('clerp')
    
    return golden_features

def extract_autogenerated_features(explanations_dir: Path) -> Dict[Tuple[str, int], str]:
    """Extract feature->label mapping from autogenerated explanations."""
    autogen_features = {}
    
    # Pattern to match files like "layers.0.mlp_latent1373.txt"
    pattern = re.compile(r'layers\.(\d+)\.mlp_latent(\d+)\.txt')
    
    for file_path in explanations_dir.glob('*.txt'):
        match = pattern.match(file_path.name)
        if match:
            layer, feature = match.groups()
            key = (layer, int(feature))
            
            # Read the explanation
            try:
                content = file_path.read_text().strip()
                # Remove the arrow and quotes if present
                if content.startswith('     1→"') and content.endswith('"'):
                    content = content[8:-1]  # Remove '     1→"' and final '"'
                autogen_features[key] = content
            except Exception as e:
                print(f"Error reading {file_path}: {e}")
                continue
    
    return autogen_features

def calculate_length_metrics(golden_label: str, autogen_label: str) -> Dict[str, float]:
    """Calculate length-based metrics."""
    golden_words = len(golden_label.split())
    autogen_words = len(autogen_label.split())
    
    return {
        'golden_word_count': golden_words,
        'autogen_word_count': autogen_words,
        'word_count_ratio': autogen_words / max(golden_words, 1),
        'length_score': 1.0 / max(1.0, autogen_words / max(golden_words, 1))  # Penalize verbosity
    }

def calculate_semantic_similarity(golden_label: str, autogen_label: str) -> float:
    """Calculate semantic similarity using enhanced methods."""
    try:
        from enhanced_semantic_evaluation import SemanticEvaluator
        evaluator = SemanticEvaluator()
        results = evaluator.evaluate(golden_label, autogen_label)
        return results['combined']
    except ImportError:
        # Fallback to word overlap if enhanced evaluator not available
        golden_words = set(golden_label.lower().split())
        autogen_words = set(autogen_label.lower().split())
        
        if not golden_words and not autogen_words:
            return 1.0
        
        intersection = golden_words.intersection(autogen_words)
        union = golden_words.union(autogen_words)
        
        return len(intersection) / len(union) if union else 0.0

def evaluate_labels(
    golden_path: Path,
    explanations_dir: Path,
    output_path: Optional[Path] = None
) -> pd.DataFrame:
    """Main evaluation function."""
    
    print("Extracting golden features...")
    golden_features = extract_golden_features(golden_path)
    print(f"Found {len(golden_features)} golden features")
    
    print("Extracting autogenerated features...")
    autogen_features = extract_autogenerated_features(explanations_dir)
    print(f"Found {len(autogen_features)} autogenerated features")
    
    # Find overlapping features
    overlap = set(golden_features.keys()) & set(autogen_features.keys())
    print(f"Found {len(overlap)} overlapping features for evaluation")
    
    if not overlap:
        print("No overlapping features found!")
        return pd.DataFrame()
    
    # Evaluate each overlapping feature
    results = []
    
    for key in overlap:
        golden_label = golden_features[key]
        autogen_label = autogen_features[key]
        
        # Calculate metrics
        length_metrics = calculate_length_metrics(golden_label, autogen_label)
        semantic_sim = calculate_semantic_similarity(golden_label, autogen_label)
        
        result = {
            'layer': key[0],
            'feature': key[1],
            'golden_label': golden_label,
            'autogen_label': autogen_label,
            'semantic_similarity': semantic_sim,
            **length_metrics
        }
        
        results.append(result)
    
    # Convert to DataFrame
    df = pd.DataFrame(results)
    
    # Calculate summary statistics
    print("\n=== EVALUATION SUMMARY ===")
    print(f"Features evaluated: {len(results)}")
    print(f"Average word count - Golden: {df['golden_word_count'].mean():.1f}, Autogen: {df['autogen_word_count'].mean():.1f}")
    print(f"Average word count ratio: {df['word_count_ratio'].mean():.2f}")
    print(f"Average semantic similarity: {df['semantic_similarity'].mean():.3f}")
    print(f"Average length score: {df['length_score'].mean():.3f}")
    
    # Show some examples
    print(f"\n=== SAMPLE COMPARISONS ===")
    sample_df = df.sample(min(10, len(df))).sort_values('semantic_similarity', ascending=False)
    
    for _, row in sample_df.iterrows():
        print(f"\nFeature {row['layer']}.{row['feature']}:")
        print(f"  Golden: '{row['golden_label']}'")
        print(f"  Autogen: '{row['autogen_label']}'")
        print(f"  Similarity: {row['semantic_similarity']:.3f}, Length Score: {row['length_score']:.3f}")
    
    # Show best and worst cases
    print(f"\n=== BEST MATCHES (by semantic similarity) ===")
    best = df.nlargest(5, 'semantic_similarity')
    for _, row in best.iterrows():
        print(f"Feature {row['layer']}.{row['feature']} (sim={row['semantic_similarity']:.3f}):")
        print(f"  Golden: '{row['golden_label']}'")
        print(f"  Autogen: '{row['autogen_label']}'")
    
    print(f"\n=== WORST MATCHES (by semantic similarity) ===")
    worst = df.nsmallest(5, 'semantic_similarity')
    for _, row in worst.iterrows():
        print(f"Feature {row['layer']}.{row['feature']} (sim={row['semantic_similarity']:.3f}):")
        print(f"  Golden: '{row['golden_label']}'")
        print(f"  Autogen: '{row['autogen_label']}'")
    
    print(f"\n=== MOST VERBOSE (by word count ratio) ===")
    verbose = df.nlargest(5, 'word_count_ratio')
    for _, row in verbose.iterrows():
        print(f"Feature {row['layer']}.{row['feature']} (ratio={row['word_count_ratio']:.1f}x):")
        print(f"  Golden: '{row['golden_label']}'")
        print(f"  Autogen: '{row['autogen_label'][:100]}{'...' if len(row['autogen_label']) > 100 else ''}")
    
    # Save results if output path provided
    if output_path:
        df.to_csv(output_path, index=False)
        print(f"\nResults saved to {output_path}")
    
    return df

def main():
    parser = argparse.ArgumentParser(description="Evaluate label quality")
    parser.add_argument(
        "--golden-graph",
        type=Path,
        default=Path("gemma-michael-jordan_2025-09-09T16-08-55-746Z.json"),
        help="Path to golden labels graph JSON"
    )
    parser.add_argument(
        "--explanations-dir", 
        type=Path,
        default=Path("results/quantized_32b_run/explanations"),
        help="Directory containing autogenerated explanations"
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Output CSV file for detailed results"
    )
    parser.add_argument(
        "--experiment-id",
        type=str,
        help="Experiment ID to record results for"
    )
    
    args = parser.parse_args()
    
    # Validate input files
    if not args.golden_graph.exists():
        print(f"Golden graph file not found: {args.golden_graph}")
        return
    
    if not args.explanations_dir.exists():
        print(f"Explanations directory not found: {args.explanations_dir}")
        return
    
    # Run evaluation
    df = evaluate_labels(args.golden_graph, args.explanations_dir, args.output)
    
    # Record results in experiment tracker if experiment ID provided
    if args.experiment_id and args.output:
        try:
            from experiment_tracker import record_results
            record_results(args.experiment_id, args.output, args.explanations_dir)
        except ImportError:
            print("⚠️  experiment_tracker.py not found, skipping experiment recording")

if __name__ == "__main__":
    main()