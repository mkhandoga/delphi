async def llm_judge_labels(golden_label: str, autogen_label: str, client=None) -> Tuple[int, str]:
    """
    Use an LLM to judge label quality. 
    Returns rating (1-5) and explanation.
    
    For now, returns a placeholder rating based on semantic similarity.
    In production, you'd integrate with your LLM client.
    """
    
    # Placeholder implementation - replace with actual LLM call
    # This simulates LLM judging based on our simple metrics
    
    similarity = calculate_semantic_similarity(golden_label, autogen_label)
    length_metrics = calculate_length_metrics(golden_label, autogen_label)
    
    # Simple heuristic to simulate LLM judgment
    if similarity > 0.3 and length_metrics['word_count_ratio'] < 3:
        rating = 5
        explanation = "Good match with appropriate length"
    elif similarity > 0.2:
        rating = 4
        explanation = "Good conceptual match but could be more concise"
    elif similarity > 0.1:
        rating = 3
        explanation = "Related concept but missing precision"
    elif similarity > 0.05:
        rating = 2
        explanation = "Partially related but significantly off-target"
    else:
        rating = 1
        explanation = "Poor match or too generic"
    
    # Penalize extreme verbosity
    if length_metrics['word_count_ratio'] > 20:
        rating = max(1, rating - 2)
        explanation += " and extremely verbose"
    elif length_metrics['word_count_ratio'] > 10:
        rating = max(1, rating - 1)
        explanation += " and too verbose"
    
    return rating, explanation

async def evaluate_labels_with_llm(
    golden_path: Path,
    explanations_dir: Path,
    output_path: Optional[Path] = None,
    use_llm_judge: bool = False
) -> pd.DataFrame:
    """Enhanced evaluation function with LLM judging."""
    
    print("Extracting golden features...")
    golden_features = extract_golden_features(golden_path)
    print(f"Found {len(golden_features)} golden features")
    
    print("Extracting autogenerated features...")
    autogen_features = extract_autogenerated_features(explanations_dir)
    print(f"Found {len(autogen_features)} autogenerated features")
    
    # Find overlapping features
    overlap = set(golden_features.keys()) & set(autogen_features.keys())
    print(f"Found {len(overlap)} overlapping features for evaluation")
    
    if not overlap:
        print("No overlapping features found!")
        return pd.DataFrame()
    
    # Evaluate each overlapping feature
    results = []
    
    for i, key in enumerate(overlap):
        golden_label = golden_features[key]
        autogen_label = autogen_features[key]
        
        print(f"Evaluating {i+1}/{len(overlap)}: {key}")
        
        # Calculate basic metrics
        length_metrics = calculate_length_metrics(golden_label, autogen_label)
        semantic_sim = calculate_semantic_similarity(golden_label, autogen_label)
        
        # LLM judge rating
        if use_llm_judge:
            llm_rating, llm_explanation = await llm_judge_labels(golden_label, autogen_label)
        else:
            llm_rating, llm_explanation = None, None
        
        result = {
            'layer': key[0],
            'feature': key[1],
            'golden_label': golden_label,
            'autogen_label': autogen_label,
            'semantic_similarity': semantic_sim,
            'llm_rating': llm_rating,
            'llm_explanation': llm_explanation,
            **length_metrics
        }
        
        results.append(result)
    
    # Convert to DataFrame
    df = pd.DataFrame(results)
    
    # Calculate summary statistics
    print("\n=== ENHANCED EVALUATION SUMMARY ===")
    print(f"Features evaluated: {len(results)}")
    print(f"Average word count - Golden: {df['golden_word_count'].mean():.1f}, Autogen: {df['autogen_word_count'].mean():.1f}")
    print(f"Average word count ratio: {df['word_count_ratio'].mean():.2f}")
    print(f"Average semantic similarity: {df['semantic_similarity'].mean():.3f}")
    print(f"Average length score: {df['length_score'].mean():.3f}")
    
    if use_llm_judge and df['llm_rating'].notna().any():
        print(f"Average LLM rating: {df['llm_rating'].mean():.2f}/5")
        print(f"LLM ratings distribution:")
        for rating in [1, 2, 3, 4, 5]:
            count = (df['llm_rating'] == rating).sum()
            pct = count / len(df) * 100
            print(f"  {rating}/5: {count} ({pct:.1f}%)")
    
    # Identify improvement opportunities
    print(f"\n=== IMPROVEMENT OPPORTUNITIES ===")
    
    # Most verbose labels
    very_verbose = df[df['word_count_ratio'] > 15]
    print(f"Very verbose labels (>15x golden length): {len(very_verbose)}")
    
    # Generic descriptions
    generic_terms = ['variety', 'common', 'often', 'frequently', 'specific', 'various', 'different']
    df['generic_score'] = df['autogen_label'].apply(
        lambda x: sum(term in x.lower() for term in generic_terms)
    )
    generic_labels = df[df['generic_score'] >= 3]
    print(f"Generic labels (≥3 generic terms): {len(generic_labels)}")
    
    # Show examples of each issue
    if len(very_verbose) > 0:
        print(f"\nMost verbose example:")
        worst_verbose = very_verbose.loc[very_verbose['word_count_ratio'].idxmax()]
        print(f"  Golden: '{worst_verbose['golden_label']}'")
        print(f"  Autogen: '{worst_verbose['autogen_label'][:100]}...'")
        print(f"  Ratio: {worst_verbose['word_count_ratio']:.1f}x")
    
    if len(generic_labels) > 0:
        print(f"\nMost generic example:")
        most_generic = generic_labels.loc[generic_labels['generic_score'].idxmax()]
        print(f"  Golden: '{most_generic['golden_label']}'")
        print(f"  Autogen: '{most_generic['autogen_label'][:100]}...'")
        print(f"  Generic terms: {most_generic['generic_score']}")
    
    # Save results
    if output_path:
        df.to_csv(output_path, index=False)
        print(f"\nEnhanced results saved to {output_path}")
    
    return df

def generate_improvement_recommendations(df: pd.DataFrame) -> List[str]:
    """Generate specific recommendations for improving the labeling system."""
    
    recommendations = []
    
    # Verbosity issues
    avg_ratio = df['word_count_ratio'].mean()
    if avg_ratio > 10:
        recommendations.append(
            f"🎯 CRITICAL: Reduce verbosity - labels are {avg_ratio:.1f}x longer than golden standard. "
            f"Add explicit length constraints to prompts (e.g., 'in 1-3 words')."
        )
    
    # Generic language
    df['generic_score'] = df['autogen_label'].apply(
        lambda x: sum(term in x.lower() for term in ['variety', 'common', 'often', 'frequently', 'specific', 'various', 'different'])
    )
    high_generic = (df['generic_score'] >= 2).sum()
    if high_generic > len(df) * 0.3:
        recommendations.append(
            f"🎯 HIGH: Reduce generic language - {high_generic}/{len(df)} labels use vague terms. "
            f"Add examples of specific vs generic labels to prompts."
        )
    
    # Low semantic similarity
    avg_similarity = df['semantic_similarity'].mean()
    if avg_similarity < 0.1:
        recommendations.append(
            f"🎯 HIGH: Improve conceptual accuracy - very low similarity ({avg_similarity:.3f}). "
            f"Consider using contrastive examples or chain-of-thought reasoning."
        )
    
    # LLM rating insights
    if 'llm_rating' in df.columns and df['llm_rating'].notna().any():
        avg_rating = df['llm_rating'].mean()
        if avg_rating < 2.5:
            recommendations.append(
                f"🎯 CRITICAL: Overall quality poor (avg rating: {avg_rating:.1f}/5). "
                f"Major prompt redesign needed."
            )
    
    # Positive findings
    best_matches = df.nlargest(5, 'semantic_similarity')
    if not best_matches.empty:
        best_features = best_matches[['golden_label', 'semantic_similarity']].values
        recommendations.append(
            f"✅ POSITIVE: Some good matches found - study these patterns for improvement."
        )
    
    return recommendations

