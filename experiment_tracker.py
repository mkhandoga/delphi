#!/usr/bin/env python3
"""
Experiment Tracking System for Prompt Optimization

Tracks prompts, scores, and metadata for systematic comparison.
"""

import json
import hashlib
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Any
import pandas as pd
import os

try:
    import wandb
    WANDB_AVAILABLE = True
except ImportError:
    WANDB_AVAILABLE = False

class PromptExperiment:
    """Represents a single prompt optimization experiment."""
    
    def __init__(self, 
                 experiment_id: str,
                 prompt_text: str,
                 prompt_version: str,
                 description: str = ""):
        self.experiment_id = experiment_id
        self.prompt_text = prompt_text
        self.prompt_version = prompt_version
        self.description = description
        self.timestamp = datetime.now().isoformat()
        self.results = {}
        self.metadata = {}
        self.sample_outputs = []
    
    def add_evaluation_results(self, results: Dict[str, Any]):
        """Add evaluation metrics from label_evaluation.py"""
        self.results.update(results)
    
    def add_sample_outputs(self, samples: List[Dict[str, str]]):
        """Add sample golden vs autogenerated comparisons"""
        self.sample_outputs = samples
    
    def add_metadata(self, **kwargs):
        """Add run metadata (model, params, etc.)"""
        self.metadata.update(kwargs)
    
    def to_dict(self) -> Dict:
        """Convert to dictionary for JSON storage"""
        return {
            'experiment_id': self.experiment_id,
            'timestamp': self.timestamp,
            'prompt_version': self.prompt_version,
            'description': self.description,
            'prompt_text': self.prompt_text,
            'results': self.results,
            'metadata': self.metadata,
            'sample_outputs': self.sample_outputs
        }

class ExperimentTracker:
    """Manages prompt optimization experiments."""
    
    def __init__(self, 
                 experiments_dir: Path = None,
                 use_wandb: bool = True,
                 wandb_project: str = "delphi-prompt-optimization",
                 wandb_entity: str = None):
        self.experiments_dir = experiments_dir or Path("prompt_experiments")
        self.experiments_dir.mkdir(exist_ok=True)
        self.index_file = self.experiments_dir / "experiment_index.json"
        self.summary_file = self.experiments_dir / "experiment_summary.csv"
        
        # Wandb configuration
        self.use_wandb = use_wandb and WANDB_AVAILABLE
        self.wandb_project = wandb_project
        self.wandb_entity = wandb_entity
        
        if self.use_wandb:
            # Check if already logged in or initialize
            if not wandb.api.api_key:
                print("⚠️  Wandb not configured. Run 'wandb login' or set WANDB_API_KEY")
                print("   Falling back to local-only tracking")
                self.use_wandb = False
        elif use_wandb and not WANDB_AVAILABLE:
            print("⚠️  Wandb not installed. Run 'pip install wandb' for enhanced tracking")
            print("   Using local-only tracking")
    
    def create_experiment(self, 
                         prompt_text: str,
                         prompt_version: str,
                         description: str = "") -> PromptExperiment:
        """Create a new experiment with unique ID."""
        
        # Generate unique ID from prompt hash + timestamp
        prompt_hash = hashlib.md5(prompt_text.encode()).hexdigest()[:8]
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        experiment_id = f"{prompt_version}_{timestamp}_{prompt_hash}"
        
        return PromptExperiment(
            experiment_id=experiment_id,
            prompt_text=prompt_text,
            prompt_version=prompt_version,
            description=description
        )
    
    def save_experiment(self, experiment: PromptExperiment):
        """Save experiment to disk and wandb."""
        
        # Save individual experiment file
        exp_file = self.experiments_dir / f"{experiment.experiment_id}.json"
        with open(exp_file, 'w') as f:
            json.dump(experiment.to_dict(), f, indent=2)
        
        # Update index
        self._update_index(experiment)
        
        # Update summary CSV
        self._update_summary()
        
        # Log to wandb if configured
        if self.use_wandb:
            self._log_to_wandb(experiment)
        
        print(f"✅ Saved experiment: {experiment.experiment_id}")
        print(f"   Version: {experiment.prompt_version}")
        print(f"   File: {exp_file}")
        if self.use_wandb:
            print(f"   Wandb: https://wandb.ai/{self.wandb_entity or 'your-entity'}/{self.wandb_project}")
    
    def _log_to_wandb(self, experiment: PromptExperiment):
        """Log experiment to Weights & Biases."""
        
        # Initialize wandb run
        run = wandb.init(
            project=self.wandb_project,
            entity=self.wandb_entity,
            name=f"{experiment.prompt_version}_{experiment.experiment_id[:8]}",
            id=experiment.experiment_id,
            resume="allow",
            config={
                "experiment_id": experiment.experiment_id,
                "prompt_version": experiment.prompt_version,
                "description": experiment.description,
                "timestamp": experiment.timestamp,
                **experiment.metadata
            }
        )
        
        # Log the prompt text as an artifact
        prompt_artifact = wandb.Artifact(
            f"prompt_{experiment.prompt_version}",
            type="prompt",
            description=experiment.description
        )
        
        # Create temporary file for prompt text
        prompt_file = self.experiments_dir / f"temp_prompt_{experiment.experiment_id}.txt"
        prompt_file.write_text(experiment.prompt_text)
        prompt_artifact.add_file(str(prompt_file))
        run.log_artifact(prompt_artifact)
        prompt_file.unlink()  # Clean up temp file
        
        # Log metrics if available
        if experiment.results:
            wandb.log({
                "semantic_similarity": experiment.results.get('avg_semantic_similarity', 0),
                "word_count_ratio": experiment.results.get('avg_word_count_ratio', 0),
                "length_score": experiment.results.get('avg_length_score', 0),
                "features_evaluated": experiment.results.get('features_evaluated', 0),
                "best_semantic_similarity": experiment.results.get('best_semantic_similarity', 0),
                "worst_semantic_similarity": experiment.results.get('worst_semantic_similarity', 0),
            })
            
            # Create comparison tables for sample outputs
            if experiment.sample_outputs:
                self._log_sample_outputs_to_wandb(experiment.sample_outputs)
        
        # Log prompt text as summary for easy viewing
        run.summary["prompt_preview"] = experiment.prompt_text[:200] + "..." if len(experiment.prompt_text) > 200 else experiment.prompt_text
        
        wandb.finish()
    
    def _log_sample_outputs_to_wandb(self, sample_outputs: Dict):
        """Log sample outputs as wandb tables."""
        
        # Best matches table
        if 'best_matches' in sample_outputs:
            best_data = []
            for sample in sample_outputs['best_matches']:
                best_data.append([
                    sample.get('golden_label', ''),
                    sample.get('autogen_label', ''),
                    sample.get('semantic_similarity', 0)
                ])
            
            best_table = wandb.Table(
                columns=["Golden Label", "Generated Label", "Similarity"],
                data=best_data
            )
            wandb.log({"best_matches": best_table})
        
        # Worst matches table
        if 'worst_matches' in sample_outputs:
            worst_data = []
            for sample in sample_outputs['worst_matches']:
                worst_data.append([
                    sample.get('golden_label', ''),
                    sample.get('autogen_label', ''),
                    sample.get('semantic_similarity', 0)
                ])
            
            worst_table = wandb.Table(
                columns=["Golden Label", "Generated Label", "Similarity"],
                data=worst_data
            )
            wandb.log({"worst_matches": worst_table})
    
    def _update_index(self, experiment: PromptExperiment):
        """Update the experiment index file."""
        
        # Load existing index
        if self.index_file.exists():
            with open(self.index_file, 'r') as f:
                index = json.load(f)
        else:
            index = {"experiments": []}
        
        # Add new experiment (or update if exists)
        exp_summary = {
            'experiment_id': experiment.experiment_id,
            'timestamp': experiment.timestamp,
            'prompt_version': experiment.prompt_version,
            'description': experiment.description,
            'file': f"{experiment.experiment_id}.json"
        }
        
        # Remove existing entry if updating
        index['experiments'] = [e for e in index['experiments'] 
                               if e['experiment_id'] != experiment.experiment_id]
        index['experiments'].append(exp_summary)
        
        # Sort by timestamp
        index['experiments'].sort(key=lambda x: x['timestamp'], reverse=True)
        
        # Save index
        with open(self.index_file, 'w') as f:
            json.dump(index, f, indent=2)
    
    def _update_summary(self):
        """Update the experiment summary CSV."""
        
        if not self.index_file.exists():
            return
        
        with open(self.index_file, 'r') as f:
            index = json.load(f)
        
        summary_data = []
        for exp_info in index['experiments']:
            exp_file = self.experiments_dir / exp_info['file']
            if exp_file.exists():
                with open(exp_file, 'r') as f:
                    exp_data = json.load(f)
                
                # Extract key metrics for CSV
                row = {
                    'experiment_id': exp_data['experiment_id'],
                    'timestamp': exp_data['timestamp'],
                    'prompt_version': exp_data['prompt_version'],
                    'description': exp_data['description'],
                }
                
                # Add evaluation results
                results = exp_data.get('results', {})
                row.update({
                    'avg_semantic_similarity': results.get('avg_semantic_similarity'),
                    'avg_word_count_ratio': results.get('avg_word_count_ratio'),
                    'avg_length_score': results.get('avg_length_score'),
                    'features_evaluated': results.get('features_evaluated'),
                })
                
                # Add metadata
                metadata = exp_data.get('metadata', {})
                row.update({
                    'model': metadata.get('model'),
                    'run_name': metadata.get('run_name'),
                })
                
                summary_data.append(row)
        
        # Save CSV
        if summary_data:
            df = pd.DataFrame(summary_data)
            df.to_csv(self.summary_file, index=False)
    
    def list_experiments(self) -> List[Dict]:
        """List all experiments."""
        if not self.index_file.exists():
            return []
        
        with open(self.index_file, 'r') as f:
            index = json.load(f)
        
        return index['experiments']
    
    def get_experiment(self, experiment_id: str) -> Optional[Dict]:
        """Get specific experiment data."""
        exp_file = self.experiments_dir / f"{experiment_id}.json"
        if not exp_file.exists():
            return None
        
        with open(exp_file, 'r') as f:
            return json.load(f)
    
    def compare_experiments(self, experiment_ids: List[str]) -> pd.DataFrame:
        """Compare multiple experiments."""
        comparison_data = []
        
        for exp_id in experiment_ids:
            exp_data = self.get_experiment(exp_id)
            if exp_data:
                row = {
                    'experiment_id': exp_id,
                    'version': exp_data['prompt_version'],
                    'description': exp_data['description'][:50] + '...' if len(exp_data['description']) > 50 else exp_data['description'],
                }
                
                results = exp_data.get('results', {})
                row.update({
                    'semantic_sim': results.get('avg_semantic_similarity', 0),
                    'word_ratio': results.get('avg_word_count_ratio', 0),
                    'length_score': results.get('avg_length_score', 0),
                })
                
                comparison_data.append(row)
        
        return pd.DataFrame(comparison_data)
    
    def get_best_experiment(self, metric: str = 'avg_semantic_similarity') -> Optional[Dict]:
        """Get the best performing experiment by a metric."""
        experiments = self.list_experiments()
        best_score = -1
        best_exp = None
        
        for exp_info in experiments:
            exp_data = self.get_experiment(exp_info['experiment_id'])
            if exp_data:
                score = exp_data.get('results', {}).get(metric, -1)
                if score > best_score:
                    best_score = score
                    best_exp = exp_data
        
        return best_exp

def run_experiment_pipeline(prompt_text: str, 
                           prompt_version: str,
                           description: str,
                           run_name: str,
                           model: str = "unknown") -> str:
    """Complete pipeline: save prompt, run evaluation, save results."""
    
    tracker = ExperimentTracker()
    
    # Create experiment
    experiment = tracker.create_experiment(
        prompt_text=prompt_text,
        prompt_version=prompt_version,
        description=description
    )
    
    # Add metadata
    experiment.add_metadata(
        model=model,
        run_name=run_name,
        golden_graph="gemma-michael-jordan_2025-09-09T16-08-55-746Z.json"
    )
    
    print(f"🧪 Created experiment: {experiment.experiment_id}")
    print(f"📝 Description: {description}")
    print(f"🔄 Next: Run Delphi with this prompt, then call record_results()")
    
    # Save experiment (will be updated with results later)
    tracker.save_experiment(experiment)
    
    return experiment.experiment_id

def detect_model_from_run_dir(explanations_dir: Path) -> Dict[str, str]:
    """Detect the model used by looking at the run config."""
    
    model_info = {
        "explainer_model": "unknown",
        "base_model": "unknown", 
        "run_name": "unknown"
    }
    
    # Look for run_config.json in parent directories
    current_dir = explanations_dir
    for _ in range(3):  # Check up to 3 levels up
        config_path = current_dir / "run_config.json"
        if config_path.exists():
            try:
                import json
                with open(config_path, 'r') as f:
                    config = json.load(f)
                
                model_info.update({
                    "explainer_model": config.get("explainer_model", "unknown"),
                    "base_model": config.get("model", "unknown"),
                    "run_name": config.get("name", current_dir.name)
                })
                break
            except Exception as e:
                print(f"⚠️  Error reading {config_path}: {e}")
        
        current_dir = current_dir.parent
        if current_dir == current_dir.parent:  # Reached root
            break
    
    return model_info

def record_results(experiment_id: str, results_csv_path: Path, explanations_dir: Path = None):
    """Record evaluation results for an experiment."""
    
    tracker = ExperimentTracker()
    experiment_data = tracker.get_experiment(experiment_id)
    
    if not experiment_data:
        print(f"❌ Experiment {experiment_id} not found")
        return
    
    # Load evaluation results
    if not results_csv_path.exists():
        print(f"❌ Results file not found: {results_csv_path}")
        return
    
    # Auto-detect model info if explanations_dir provided
    model_info = {}
    if explanations_dir:
        model_info = detect_model_from_run_dir(explanations_dir)
    
    df = pd.read_csv(results_csv_path)
    
    # Calculate summary metrics
    results = {
        'avg_semantic_similarity': df['semantic_similarity'].mean(),
        'avg_word_count_ratio': df['word_count_ratio'].mean(),
        'avg_length_score': df['length_score'].mean(),
        'features_evaluated': len(df),
        'best_semantic_similarity': df['semantic_similarity'].max(),
        'worst_semantic_similarity': df['semantic_similarity'].min(),
    }
    
    # Get sample outputs (best and worst cases)
    best_samples = df.nlargest(3, 'semantic_similarity')[['golden_label', 'autogen_label', 'semantic_similarity']].to_dict('records')
    worst_samples = df.nsmallest(3, 'semantic_similarity')[['golden_label', 'autogen_label', 'semantic_similarity']].to_dict('records')
    
    sample_outputs = {
        'best_matches': best_samples,
        'worst_matches': worst_samples
    }
    
    # Update experiment
    experiment = PromptExperiment(
        experiment_id=experiment_data['experiment_id'],
        prompt_text=experiment_data['prompt_text'],
        prompt_version=experiment_data['prompt_version'],
        description=experiment_data['description']
    )
    experiment.timestamp = experiment_data['timestamp']
    experiment.add_evaluation_results(results)
    experiment.add_sample_outputs(sample_outputs)
    
    # Merge existing metadata with detected model info
    combined_metadata = {**experiment_data['metadata'], **model_info}
    experiment.add_metadata(**combined_metadata)
    
    # Save updated experiment
    tracker.save_experiment(experiment)
    
    print(f"✅ Recorded results for {experiment_id}")
    print(f"📊 Semantic similarity: {results['avg_semantic_similarity']:.3f}")
    print(f"📏 Word count ratio: {results['avg_word_count_ratio']:.1f}")
    print(f"🎯 Length score: {results['avg_length_score']:.3f}")

